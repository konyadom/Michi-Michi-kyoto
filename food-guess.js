export function quantityHint(text){
 const t=String(text||'').normalize('NFKC');let q=1,label='';
 const n=t.match(/(\d+(?:\.\d+)?)\s*(個|本|杯|枚|皿|人前|切れ|パック|袋|貫|つ)/);if(n){q=Number(n[1]);label=n[1]+n[2];}
 if(/特盛|メガ|ダブル/.test(t)){q*=1.6;label+=(label?' ':'')+'特盛';}
 else if(/大盛|大|L\b|ラージ/.test(t)){q*=1.3;label+=(label?' ':'')+'大盛';}
 else if(/半分|ハーフ|半/.test(t)){q*=.5;label+=(label?' ':'')+'半分';}
 else if(/小盛|ミニ|小|S\b/.test(t)){q*=.7;label+=(label?' ':'')+'小';}
 return {quantity:Number(q.toFixed(2)),label};
}
export function guessFood(text,meal='lunch'){
 const t=String(text||'').normalize('NFKC').trim();if(!t)return [];
 const {quantity,label}=quantityHint(t),out=[];
 for(const rule of RULES){if(rule.re.test(t)){out.push({id:'guess-'+out.length,name:rule.name,unit:rule.unit,quantity,nutrients:{...rule.n},evidence:'estimate',source:'',note:'入力「'+t+'」からの概算。'+(rule.note?rule.note+'。':'')+(label?'量：'+label+'。':'')+'数値はあとで直せる。',guess:true,matched:rule.name});if(out.length>=2)break;}}
 if(!out.length)out.push({id:'guess-unknown',name:t.slice(0,40)+'（概算）',unit:'食',quantity:1,nutrients:{...MEAL_DEFAULT[meal]||MEAL_DEFAULT.lunch},evidence:'estimate',source:'',note:'中身が分からないので'+(MEAL_LABEL[meal]||'1食')+'の平均的な値を入れた概算。分かったら編集で直せる。',guess:true,unknown:true});
 return out;
}
// Open Food Facts（投稿データベース）。100gあたりの値で返す。つながらないときは空。
export async function searchOnlineFood(text,signal){
 const q=String(text||'').trim();if(q.length<2)return [];
 const url='https://world.openfoodfacts.org/cgi/search.pl?search_terms='+encodeURIComponent(q)+'&search_simple=1&action=process&json=1&page_size=6&fields=code,product_name,product_name_ja,brands,nutriments';
 const res=await fetch(url,{signal,credentials:'omit'});if(!res.ok)throw Error('検索できなかった');
 const json=await res.json(),list=[];
 for(const p of json.products||[]){const n=p.nutriments||{},kcal=Number(n['energy-kcal_100g']);if(!Number.isFinite(kcal))continue;const name=(p.product_name_ja||p.product_name||'').trim();if(!name)continue;
  const num=k=>Number.isFinite(Number(n[k]))?Number(n[k])/100:null;
  list.push({id:'off-'+p.code,name:(p.brands?p.brands.split(',')[0].trim()+' ':'')+name,unit:'g',quantity:100,nutrients:{energy:kcal/100,protein:num('proteins_100g'),fat:num('fat_100g'),saturated:num('saturated-fat_100g'),carb:num('carbohydrates_100g'),fiber:num('fiber_100g'),salt:num('salt_100g')},evidence:'label',source:'https://world.openfoodfacts.org/product/'+encodeURIComponent(p.code),note:'Open Food Facts の投稿データ。100gあたり。食べた量に合わせて数を直す。',online:true});
  if(list.length>=4)break;}
 return list;
}
